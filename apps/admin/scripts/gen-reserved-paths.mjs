// Scans apps/web/src/app and emits the list of first URL segments already used
// by real pages, so the live-course custom-path validator can reject collisions.
// Run via `pnpm --filter admin gen:reserved-paths` (also wired to prebuild).
import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP_DIR = resolve(__dirname, "../../web/src/app");
const OUT_FILE = resolve(__dirname, "../src/features/live-courses/reserved-paths.generated.ts");

/**
 * Collect the first URL segment of every route. Route groups `(x)` don't add a
 * segment (we recurse into them); dynamic `[x]` / private `_x` folders and files
 * are skipped. Blocking a first segment also blocks everything nested under it.
 */
function collectFirstSegments(dir) {
  const out = new Set();
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (!statSync(full).isDirectory()) continue;
    if (entry.startsWith("_") || entry.startsWith(".")) continue;
    if (entry.startsWith("[")) continue; // dynamic segment — not a reserved literal
    if (entry.startsWith("(") && entry.endsWith(")")) {
      for (const s of collectFirstSegments(full)) out.add(s);
      continue;
    }
    out.add(entry.toLowerCase());
  }
  return out;
}

const segments = [...collectFirstSegments(APP_DIR)].sort();

const content = `// AUTO-GENERATED by scripts/gen-reserved-paths.mjs — do not edit by hand.
// Run \`pnpm --filter admin gen:reserved-paths\` to refresh.
// First URL segments already used by real pages in apps/web. A live-course
// custom path may not start with any of these.
export const RESERVED_FIRST_SEGMENTS: readonly string[] = ${JSON.stringify(segments, null, 2)};
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, content, "utf8");
console.log(`gen-reserved-paths: wrote ${segments.length} segments → ${OUT_FILE}`);
